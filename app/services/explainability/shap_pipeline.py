def permutation_validation(ctx: RunContext, global_df: pd.DataFrame) -> tuple[pd.DataFrame, dict[str, Any]]:
    indices = select_rows(ctx, int(ctx.config["max_permutation_rows"]))
    Xp = ctx.X.iloc[indices].copy()
    yp = ctx.y.iloc[indices].to_numpy()
    baseline = ctx.model.predict(make_dmatrix(Xp))
    baseline_auc = roc_auc_score(yp, baseline)
    repeats = int(ctx.config["permutation_repeats"])
    rows = []
    feature_type_lookup = dict(zip(ctx.features, ctx.feature_types))
    for feature in ctx.features:
        drops = []
        for _ in range(repeats):
            shuffled = Xp.copy()
            if feature_type_lookup[feature] == "c":
                permuted = ctx.rng.permutation(shuffled[feature].astype(object).to_numpy())
                shuffled[feature] = pd.Categorical(permuted, categories=Xp[feature].cat.categories)
            else:
                permuted = ctx.rng.permutation(shuffled[feature].to_numpy())
                shuffled[feature] = permuted
            pred = ctx.model.predict(make_dmatrix(shuffled))
            drops.append(baseline_auc - roc_auc_score(yp, pred))
        rows.append({"feature": feature, "permutation_auc_drop": float(np.mean(drops))})
    result = pd.DataFrame(rows).sort_values("permutation_auc_drop", ascending=False).reset_index(drop=True)
    result.insert(0, "permutation_rank", np.arange(1, len(result) + 1))
    result = result.merge(global_df[["feature", "rank", "mean_abs_shap"]], on="feature", how="left")
    result = result.rename(columns={"rank": "shap_rank"})
    result["rank_difference"] = (result["permutation_rank"] - result["shap_rank"]).abs()
    corr = spearmanr(result["shap_rank"], result["permutation_rank"]).statistic
    k = min(20, len(result))
    shap_top = set(result.nsmallest(k, "shap_rank")["feature"])
    perm_top = set(result.nsmallest(k, "permutation_rank")["feature"])
    jaccard = len(shap_top & perm_top) / len(shap_top | perm_top)
    summary = {
        "sample_size": len(indices),
        "baseline_auc": float(baseline_auc),
        "spearman": float(corr),
        "top20_jaccard": float(jaccard),
        "status": status_min(float(corr), ctx.config["thresholds"]["permutation_spearman_min"]),
    }
    result.to_csv(ctx.output / "global" / "permutation_comparison.csv", index=False, encoding="utf-8-sig")
    write_json(ctx.output / "global" / "permutation_summary.json", summary)
    return result, summary


def global_stability(ctx: RunContext, shap_result: dict[str, Any]) -> tuple[pd.DataFrame, dict[str, Any]]:
    values = np.abs(shap_result["shap_values"])
    n = len(values)
    repeats = int(ctx.config["stability_repeats"])
    run_ranks = []
    reference = values.mean(axis=0)
    ref_rank = pd.Series(-reference).rank(method="average").to_numpy()
    correlations = []
    jaccards = []
    k = min(20, len(ctx.features))
    ref_top = set(np.argsort(-reference)[:k])
    for run in range(repeats):
        sampled = ctx.rng.choice(n, size=n, replace=True)
        importance = values[sampled].mean(axis=0)
        ranks = pd.Series(-importance).rank(method="average").to_numpy()
        run_ranks.append(ranks)
        correlations.append(spearmanr(ref_rank, ranks).statistic)
        top = set(np.argsort(-importance)[:k])
        jaccards.append(len(ref_top & top) / len(ref_top | top))
    ranks_matrix = np.vstack(run_ranks)
    detail = pd.DataFrame(
        {
            "feature": ctx.features,
            "mean_rank": ranks_matrix.mean(axis=0),
            "rank_std": ranks_matrix.std(axis=0),
            "top20_inclusion_rate": (ranks_matrix <= k).mean(axis=0),
        }
    ).sort_values("mean_rank")
    summary = {
        "repeats": repeats,
        "mean_spearman": float(np.mean(correlations)),
        "mean_top20_jaccard": float(np.mean(jaccards)),
        "review_threshold": ctx.config["thresholds"][
            "global_stability_spearman_review_min"
        ],
        "status": status_min(
            float(np.mean(correlations)),
            ctx.config["thresholds"]["global_stability_spearman_min"],
            ctx.config["thresholds"]["global_stability_spearman_review_min"],
        ),
    }
    detail.to_csv(ctx.output / "global" / "global_stability.csv", index=False, encoding="utf-8-sig")
    write_json(ctx.output / "global" / "global_stability_summary.json", summary)
    return detail, summary


def sensitive_audit(
    ctx: RunContext,
    shap_result: dict[str, Any],
    mapping: pd.DataFrame,
) -> tuple[pd.DataFrame, pd.DataFrame, dict[str, Any]]:
    values = np.abs(shap_result["shap_values"])
    total = values.sum()
    rows = []
    sensitive_mask = mapping["is_sensitive"].to_numpy(dtype=bool)
    for group in ctx.config["sensitive_groups"]:
        group_mask = mapping["sensitive_group"].fillna("").str.split(",").apply(lambda x: group in x).to_numpy()
        group_sum = values[:, group_mask].sum() if group_mask.any() else 0.0
        rows.append(
            {
                "sensitive_group": group,
                "model_features": ",".join(mapping.loc[group_mask, "feature"]),
                "abs_shap_sum": group_sum,
                "contribution_ratio": group_sum / total if total else np.nan,
                "directly_used_by_model": bool(group_mask.any()),
            }
        )
    detail = pd.DataFrame(rows)
    sensitive_total = values[:, sensitive_mask].sum() if sensitive_mask.any() else 0.0
    ratio = sensitive_total / total if total else np.nan
    threshold = ctx.config["thresholds"]["sensitive_contribution_ratio_max"]
    review_threshold = ctx.config["thresholds"][
        "sensitive_contribution_ratio_review_max"
    ]
    summary = {
        "value": float(ratio),
        "threshold": threshold,
        "review_threshold": review_threshold,
        "status": status_max(
            float(ratio),
            threshold,
            review_threshold,
        ),
        "note": "Direct SHAP contribution of model-input sensitive feature families only; proxy effects are not measured.",
    }
    detail.to_csv(ctx.output / "sensitive" / "sensitive_feature_audit.csv", index=False, encoding="utf-8-sig")

    per_customer_total = values.sum(axis=1)
    per_customer_sensitive = values[:, sensitive_mask].sum(axis=1) if sensitive_mask.any() else np.zeros(len(values))
    per_customer_ratio = np.divide(
        per_customer_sensitive,
        per_customer_total,
        out=np.zeros_like(per_customer_sensitive),
        where=per_customer_total != 0,
    )
    audit = ctx.raw.iloc[shap_result["row_indices"]].reset_index(drop=True)
    group_rows: list[dict[str, Any]] = []
    for group_column in ["CODE_GENDER", "AGE_GROUP"]:
        if group_column not in audit.columns:
            continue
        temp = pd.DataFrame({"group": audit[group_column].astype(str), "ratio": per_customer_ratio})
        for group_value, frame in temp.groupby("group", dropna=False):
            group_rows.append(
                {
                    "group_column": group_column,
                    "group_value": group_value,
                    "customer_count": len(frame),
                    "mean_sensitive_ratio": frame["ratio"].mean(),
                    "median_sensitive_ratio": frame["ratio"].median(),
                    "p95_sensitive_ratio": frame["ratio"].quantile(0.95),
                }
            )
    group_detail = pd.DataFrame(group_rows)
    group_detail.to_csv(ctx.output / "sensitive" / "sensitive_group_audit.csv", index=False, encoding="utf-8-sig")
    write_json(ctx.output / "sensitive" / "sensitive_summary.json", summary)
    return detail, group_detail, summary


def apply_policy_and_fidelity(
    ctx: RunContext,
    shap_result: dict[str, Any],
    mapping: pd.DataFrame,
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, dict[str, Any]]:
    include = mapping["action"].eq("INCLUDE").to_numpy()
    policy_lookup = mapping.set_index("feature").to_dict("index")
    values = shap_result["shap_values"]
    Xs = shap_result["X"].reset_index(drop=True)
    top_k = int(ctx.config["top_k"])
    final_rows = []
    filter_rows = []
    fidelity_rows = []
    for i in range(len(Xs)):
        allowed_indices = np.where(include)[0]
        allowed_order = allowed_indices[np.argsort(-np.abs(values[i, allowed_indices]))]
        chosen = allowed_order[:top_k]
        raw_top = np.argsort(-np.abs(values[i]))[:top_k]
        for j in raw_top:
            info = policy_lookup[ctx.features[j]]
            filter_rows.append(
                {
                    "customer_id": shap_result["ids"].iloc[i],
                    "feature": ctx.features[j],
                    "original_top_k": True,
                    "action": info["action"],
                    "reason": info["disclosure_policy"],
                }
            )
        for rank, j in enumerate(chosen, start=1):
            final_rows.append(
                {
                    "customer_id": shap_result["ids"].iloc[i],
                    "prediction_probability": shap_result["pred_probability"][i],
                    "rank": rank,
                    "feature": ctx.features[j],
                    "feature_value": Xs.iloc[i, j],
                    "shap_value": values[i, j],
                    "direction": "RISK_INCREASE" if values[i, j] > 0 else "RISK_DECREASE",
                }
            )
        all_abs = np.abs(values[i]).sum()
        selected_abs = np.abs(values[i, chosen]).sum()
        coverage = selected_abs / all_abs if all_abs else 1.0
        reconstructed = shap_result["base_values"][i] + values[i, chosen].sum()
        fidelity_rows.append(
            {
                "customer_id": shap_result["ids"].iloc[i],
                "model_margin": shap_result["pred_margin"][i],
                "explanation_reconstructed_margin": reconstructed,
                "absolute_margin_error": abs(shap_result["pred_margin"][i] - reconstructed),
                "absolute_contribution_coverage": coverage,
                "selected_reason_count": len(chosen),
            }
        )
    final_df = pd.DataFrame(final_rows)
    filter_df = pd.DataFrame(filter_rows)
    fidelity_df = pd.DataFrame(fidelity_rows)
    fidelity_value = float(fidelity_df["absolute_contribution_coverage"].median())
    r2 = r2_score(fidelity_df["model_margin"], fidelity_df["explanation_reconstructed_margin"])
    summary = {
        "value": fidelity_value,
        "metric": "median_absolute_contribution_coverage",
        "threshold": ctx.config["thresholds"]["explanation_fidelity_min"],
        "review_threshold": ctx.config["thresholds"][
            "explanation_fidelity_review_min"
        ],
        "status": status_min(
            fidelity_value,
            ctx.config["thresholds"]["explanation_fidelity_min"],
            ctx.config["thresholds"]["explanation_fidelity_review_min"],
        ),
        "margin_reconstruction_r2": float(r2),
        "margin_reconstruction_mae": float(fidelity_df["absolute_margin_error"].mean()),
        "top_k": top_k,
    }
    final_df.to_csv(ctx.output / "local" / "customer_final_explanations.csv", index=False, encoding="utf-8-sig")
    filter_df.to_csv(ctx.output / "validation" / "policy_filter_log.csv", index=False, encoding="utf-8-sig")
    fidelity_df.to_csv(ctx.output / "local" / "customer_fidelity.csv", index=False, encoding="utf-8-sig")
    write_json(ctx.output / "local" / "fidelity_summary.json", summary)
    return final_df, filter_df, fidelity_df, summary


def lime_validation(
    ctx: RunContext,
    shap_result: dict[str, Any],
) -> tuple[pd.DataFrame, dict[str, Any]]:
    try:
        from lime.lime_tabular import LimeTabularExplainer
    except Exception as exc:
        summary = {"status": "NOT_EVALUATED", "reason": f"LIME import failed: {exc}"}
        write_json(ctx.output / "local" / "lime_summary.json", summary)
        return pd.DataFrame(), summary

    Xs = shap_result["X"].reset_index(drop=True)
    encoded = pd.DataFrame(index=Xs.index)
    categorical_indices = []
    categorical_names: dict[int, list[str]] = {}
    category_levels: dict[str, list[Any]] = {}
    fill_values: dict[str, float] = {}
    for j, (feature, ftype) in enumerate(zip(ctx.features, ctx.feature_types)):
        if ftype == "c":
            categorical_indices.append(j)
            levels = list(Xs[feature].cat.categories)
            category_levels[feature] = levels
            categorical_names[j] = [str(v) for v in levels]
            codes = Xs[feature].cat.codes.replace(-1, np.nan).astype(float)
            mode = codes.mode()
            fill = float(mode.iloc[0]) if not mode.empty else 0.0
            fill_values[feature] = fill
            encoded[feature] = codes.fillna(fill)
        else:
            series = pd.to_numeric(Xs[feature], errors="coerce").astype(float)
            fill = float(series.median()) if series.notna().any() else 0.0
            fill_values[feature] = fill
            encoded[feature] = series.fillna(fill)

    def predict_fn(array: np.ndarray) -> np.ndarray:
        frame = pd.DataFrame(array, columns=ctx.features)
        for j, (feature, ftype) in enumerate(zip(ctx.features, ctx.feature_types)):
            if ftype == "c":
                levels = category_levels[feature]
                codes = np.clip(np.rint(frame[feature]).astype(int), 0, max(len(levels) - 1, 0))
                frame[feature] = pd.Categorical.from_codes(codes, categories=levels)
            elif ftype == "int":
                frame[feature] = pd.to_numeric(frame[feature], errors="coerce").round().astype("Int64")
            else:
                frame[feature] = pd.to_numeric(frame[feature], errors="coerce")
        probability = ctx.model.predict(make_dmatrix(frame))
        return np.column_stack([1.0 - probability, probability])

    explainer = LimeTabularExplainer(
        encoded.to_numpy(dtype=float),
        feature_names=ctx.features,
        class_names=["low_risk", "high_risk"],
        categorical_features=categorical_indices,
        categorical_names=categorical_names,
        discretize_continuous=True,
        random_state=int(ctx.config["random_seed"]),
        mode="classification",
    )
    case_count = min(int(ctx.config["lime_cases"]), len(Xs))
    probabilities = shap_result["pred_probability"]
    candidate_indices = list(dict.fromkeys([int(np.argmax(probabilities)), int(np.argmin(probabilities)), int(np.argmin(np.abs(probabilities - 0.5)))]))
    remaining = [i for i in range(len(Xs)) if i not in candidate_indices]
    if len(candidate_indices) < case_count:
        candidate_indices.extend(ctx.rng.choice(remaining, size=case_count - len(candidate_indices), replace=False).tolist())
    rows = []
    top_k = int(ctx.config["top_k"])
    for i in candidate_indices[:case_count]:
        explanation = explainer.explain_instance(
            encoded.iloc[i].to_numpy(dtype=float),
            predict_fn,
            labels=(1,),
            num_features=top_k,
            num_samples=int(ctx.config["lime_num_samples"]),
        )
        lime_features = {ctx.features[idx] for idx, _ in explanation.as_map().get(1, [])}
        shap_top_idx = np.argsort(-np.abs(shap_result["shap_values"][i]))[:top_k]
        shap_features = {ctx.features[idx] for idx in shap_top_idx}
        union = lime_features | shap_features
        overlap = len(lime_features & shap_features) / len(union) if union else 1.0
        rows.append(
            {
                "customer_id": shap_result["ids"].iloc[i],
                "prediction_probability": probabilities[i],
                "shap_top_features": ",".join(sorted(shap_features)),
                "lime_top_features": ",".join(sorted(lime_features)),
                "top_k_jaccard": overlap,
                "lime_local_r2": float(explanation.score),
            }
        )
    detail = pd.DataFrame(rows)
    mean_overlap = float(detail["top_k_jaccard"].mean()) if not detail.empty else np.nan
    summary = {
        "case_count": len(detail),
        "mean_top_k_jaccard": mean_overlap,
        "status": status_min(mean_overlap, ctx.config["thresholds"]["lime_overlap_min"]),
        "note": "LIME is a sampled local surrogate and is used only as a supplementary check.",
    }
    detail.to_csv(ctx.output / "local" / "lime_validation.csv", index=False, encoding="utf-8-sig")
    write_json(ctx.output / "local" / "lime_summary.json", summary)
    return detail, summary


