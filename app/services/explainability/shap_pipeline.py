def status_min(
    value: float | None,
    pass_threshold: float,
    review_threshold: float | None = None,
) -> str:
    if value is None or not np.isfinite(value):
        return "NOT_EVALUATED"
    if value >= pass_threshold:
        return "PASS"
    if review_threshold is not None and value < review_threshold:
        return "REVIEW"
    return "WARNING"


def status_max(
    value: float | None,
    pass_threshold: float,
    review_threshold: float | None = None,
) -> str:
    if value is None or not np.isfinite(value):
        return "NOT_EVALUATED"
    if value <= pass_threshold:
        return "PASS"
    if review_threshold is not None and value > review_threshold:
        return "REVIEW"
    return "WARNING"


def prepare_model_frame(raw: pd.DataFrame, features: list[str], feature_types: list[str]) -> pd.DataFrame:
    X = raw.loc[:, features].copy()
    for feature, ftype in zip(features, feature_types):
        if ftype == "c":
            X[feature] = X[feature].astype("category")
        elif ftype == "int":
            X[feature] = pd.to_numeric(X[feature], errors="coerce").astype("Int64")
        else:
            X[feature] = pd.to_numeric(X[feature], errors="coerce")
    return X


def make_dmatrix(X: pd.DataFrame, y: pd.Series | None = None) -> xgb.DMatrix:
    return xgb.DMatrix(X, label=y, enable_categorical=True, missing=np.nan)


def select_rows(ctx: RunContext, maximum: int) -> np.ndarray:
    n = len(ctx.X)
    size = min(maximum, n)
    return np.sort(ctx.rng.choice(n, size=size, replace=False))


def sensitive_feature_map(features: list[str], config: dict[str, Any]) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    groups: dict[str, list[str]] = config["sensitive_groups"]
    policy = config["disclosure_policy"]
    review_patterns = [x.upper() for x in policy.get("review_patterns", [])]
    for feature in features:
        upper = feature.upper()
        matched_groups = [
            group
            for group, patterns in groups.items()
            if any(pattern.upper() in upper for pattern in patterns)
        ]
        sensitive_group = ",".join(matched_groups)
        if matched_groups:
            disclosure = policy.get("sensitive_policy", "SENSITIVE")
            action = "EXCLUDE"
        elif any(pattern in upper for pattern in review_patterns):
            disclosure = "REVIEW"
            action = "REVIEW"
        else:
            disclosure = policy.get("default_model_feature_policy", "ALLOW")
            action = "INCLUDE" if disclosure == "ALLOW" else "EXCLUDE"
        rows.append(
            {
                "feature": feature,
                "sensitive_group": sensitive_group,
                "is_sensitive": bool(matched_groups),
                "disclosure_policy": disclosure,
                "action": action,
            }
        )
    return pd.DataFrame(rows)


def schema_validation(
    raw: pd.DataFrame,
    model: xgb.Booster,
    config: dict[str, Any],
) -> tuple[dict[str, Any], list[str], list[str]]:
    features = model.feature_names or []
    feature_types = model.feature_types or ["float"] * len(features)
    missing = [f for f in features if f not in raw.columns]
    required = [config["target_column"], config["id_column"]]
    missing_required = [f for f in required if f not in raw.columns]
    duplicate_columns = raw.columns[raw.columns.duplicated()].tolist()
    extra = [f for f in raw.columns if f not in features and f not in required]
    result = {
        "status": "PASS" if not missing and not missing_required and not duplicate_columns else "FAIL",
        "model_feature_count": len(features),
        "dataset_column_count": len(raw.columns),
        "row_count": len(raw),
        "missing_model_features": missing,
        "missing_required_columns": missing_required,
        "duplicate_columns": duplicate_columns,
        "audit_only_columns": extra,
    }
    return result, features, feature_types


def shap_calculation(ctx: RunContext) -> dict[str, Any]:
    rows = select_rows(ctx, int(ctx.config["max_shap_rows"]))
    Xs = ctx.X.iloc[rows]
    ys = ctx.y.iloc[rows]
    ids = ctx.ids.iloc[rows].reset_index(drop=True)
    dm = make_dmatrix(Xs, ys)
    pred_probability = ctx.model.predict(dm)
    pred_margin = ctx.model.predict(dm, output_margin=True)
    contributions = ctx.model.predict(dm, pred_contribs=True)
    shap_values = contributions[:, :-1]
    base_values = contributions[:, -1]
    reconstructed = base_values + shap_values.sum(axis=1)
    errors = np.abs(pred_margin - reconstructed)
    additivity = pd.DataFrame(
        {
            "customer_id": ids,
            "prediction_probability": pred_probability,
            "model_margin": pred_margin,
            "shap_reconstructed_margin": reconstructed,
            "absolute_error": errors,
        }
    )
    additivity.to_csv(ctx.output / "validation" / "additivity_validation.csv", index=False, encoding="utf-8-sig")
    threshold = ctx.config["thresholds"]["additivity_max_abs_error_max"]
    additivity_summary = {
        "sample_size": len(rows),
        "mean_absolute_error": float(errors.mean()),
        "max_absolute_error": float(errors.max()),
        "threshold": threshold,
        "status": status_max(float(errors.max()), threshold),
    }
    write_json(ctx.output / "validation" / "additivity_summary.json", additivity_summary)
    return {
        "row_indices": rows,
        "X": Xs,
        "y": ys,
        "ids": ids,
        "pred_probability": pred_probability,
        "pred_margin": pred_margin,
        "shap_values": shap_values,
        "base_values": base_values,
        "additivity": additivity_summary,
    }


def global_importance(ctx: RunContext, shap_result: dict[str, Any], mapping: pd.DataFrame) -> pd.DataFrame:
    values = shap_result["shap_values"]
    mean_abs = np.abs(values).mean(axis=0)
    signed_mean = values.mean(axis=0)
    total = mean_abs.sum()
    result = pd.DataFrame(
        {
            "feature": ctx.features,
            "mean_abs_shap": mean_abs,
            "mean_signed_shap": signed_mean,
            "contribution_ratio": mean_abs / total if total else np.nan,
        }
    ).merge(mapping, on="feature", how="left")
    result = result.sort_values("mean_abs_shap", ascending=False).reset_index(drop=True)
    result.insert(0, "rank", np.arange(1, len(result) + 1))
    result.to_csv(ctx.output / "global" / "global_shap_importance.csv", index=False, encoding="utf-8-sig")
    return result


